"""Render the DuoDuo mark into LVGL 9 RGB565 images for the pocket screens.

Source: assets/images/mark/logo-geometry.json, the geometry the DuoDuo web app
and phone app draw. Each frame is the still frame those apps show under reduced
motion (time 0, level 0) on the dark palette: a halo behind the mark gives the
mood's colour, the unavailable mood is grey. The frames are rasterised with
rsvg-convert on the dark page colour, so no alpha channel is needed, and
written as const lv_image_dsc_t arrays in flash.

The recording screen is the one live frame: its large hearing image has no
voice bars, and the firmware draws the five bars with LVGL lines that follow
the microphone level (main/pocket_ui.c). This script writes their geometry
into the header, so the firmware and the mockups share one source.

Outputs: assets/images/mark/pocket_mark.c and pocket_mark.h (committed) and
PNG previews under tools/pocket/.cache/mark/ for the mockup renderer.
Needs: rsvg-convert (librsvg) and Pillow.
"""
from __future__ import annotations

import json
import math
import subprocess
import sys
from io import BytesIO
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "assets/images/mark"
CACHE = REPO / "tools/pocket/.cache/mark"
GEOM = json.loads((SRC / "logo-geometry.json").read_text(encoding="utf-8"))
BG = "#0e0e0d"  # --color-bg of the dark theme, the screen background

# Dark palette of the mark (web logo-mark.js, phone LogoMark.swift).
INK, OFF, COAT, BARS, ACCENT = "#faf9f5", "#8d8c86", "#3a3835", "#1fd9de", "#f7a8c8"
TEAL, VIOLET, PINK = "#1fd9de", "#a594ff", "#f7a8c8"

# Order is the C enum order (pocket_mark_t).
MOODS = ["idle", "hearing", "thinking", "speaking", "unavailable"]
# Frame side in px. Large: state screens; small: the transcript and reply
# header. Only the moods a size is shown in are generated (main/pocket_ui.c).
SIZES = {"large": 132, "small": 50}
USED = {"large": ["idle", "hearing", "thinking", "unavailable"],
        "small": ["idle", "thinking", "speaking"]}
# Large hearing is the recording screen: bars drawn live by the firmware.
LIVE = ("large", "hearing")

# Motion of the bars with a level, from the apps' speaking-aloud mood: half
# length = rest + TALK * level * (BASE + SWING * wave), wave = 0.5 + 0.5 *
# sin(t * RATE + bar * PHASE). Logo units, seconds, radians.
TALK, BASE, SWING, RATE, PHASE = 70.0, 0.55, 0.45, 11.0, 1.7
# Still-frame bars of the other moods, from the same apps at time 0 (logo
# units): speaking adds SPEAK * wave, thinking adds THINK * (0.5 + 0.5 *
# sin(bar * THINK_PHASE)), idle dozes to (1 - DOZE) of the length.
SPEAK, THINK, THINK_PHASE, DOZE = 46.0, 14.0, 0.9, 0.6
# The mark fills this share of the frame and leaves the outer ring to the halo.
MARK_SHARE = 0.7
# Feet of the mark, the pivot of the tilt (logo units).
PIVOT = (512.0, 820.0)

HEADER = """// Copyright 2026 openduo
// SPDX-License-Identifier: FSL-1.1-Apache-2.0
// Generated by tools/pocket/gen_mark.py; do not edit.
// The DuoDuo mark is a brand asset with no open licence (NOTICE).
"""


def halo(mood: str) -> tuple[str, float] | None:
    """Colour and strength of the halo at time 0 and level 0; none while
    idle or unavailable."""
    return {"hearing": (TEAL, 0.7), "thinking": (VIOLET, 0.6),
            "speaking": (PINK, 0.65)}.get(mood)


def tilt(mood: str) -> float:
    """Head tilt in degrees at time 0."""
    return {"hearing": -14.0, "idle": -6.0}.get(mood, 0.0)


def scale(side: int) -> float:
    return side / GEOM["side"] * MARK_SHARE


def bar_halves(mood: str, level: float = 0.0, t: float = 0.0) -> list[float]:
    """Half length of each bar in logo units. level moves the live bars."""
    doze = 1.0 if mood == "idle" else 0.0
    out = []
    for i, (_, y1, y2) in enumerate(GEOM["bars"]):
        rest = (y2 - y1) / 2
        wave = 0.5 + 0.5 * math.sin(t * RATE + i * PHASE)
        talk = TALK * level * (BASE + SWING * wave)
        if mood == "speaking":
            talk += SPEAK * wave
        think = THINK * (0.5 + 0.5 * math.sin(i * THINK_PHASE)) if mood == "thinking" else 0.0
        out.append((rest + talk + think) * (1 - DOZE * doze))
    return out


def transform(side: int, mood: str) -> str:
    k = scale(side)
    c = side / 2
    off = c - GEOM["side"] * k / 2
    ox, oy = GEOM["origin"]
    px, py = PIVOT
    return (f"translate({off:.4f} {off:.4f}) scale({k:.6f}) translate({-ox} {-oy}) "
            f"translate({px} {py}) rotate({tilt(mood)}) translate({-px} {-py})")


def svg(mood: str, side: int, bars: bool = True, level: float = 0.0) -> str:
    """One frame. level moves the bars only; the halo stays the still frame's."""
    c = r = side / 2
    off = mood == "unavailable"
    line = OFF if off else INK
    bar_c = line if off else BARS
    accent = line if off else ACCENT
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{side}" height="{side}" '
             f'viewBox="0 0 {side} {side}">']
    h = halo(mood)
    if h:
        color, s = h
        # Strongest at the coat's edge (about 0.62 of the radius).
        parts.append(f'<defs><radialGradient id="h" gradientUnits="userSpaceOnUse" cx="{c}" '
                     f'cy="{c}" r="{r * 0.9}">'
                     f'<stop offset="0.6" stop-color="{color}" stop-opacity="{0.95 * s:.4f}"/>'
                     f'<stop offset="0.78" stop-color="{color}" stop-opacity="{0.5 * s:.4f}"/>'
                     f'<stop offset="1" stop-color="{color}" stop-opacity="0"/>'
                     f'</radialGradient></defs><circle cx="{c}" cy="{c}" r="{r}" fill="url(#h)"/>')
    parts.append(f'<g transform="{transform(side, mood)}">')
    pts = " ".join(f"{x},{y}" for x, y in GEOM["outline"])
    # Filled so the halo shows around the coat, not through it.
    parts.append(f'<polygon points="{pts}" fill="{COAT}" stroke="{line}" '
                 f'stroke-width="{GEOM["outlineWidth"]}" stroke-linejoin="round"/>')
    if bars:
        for i, ((x, y1, y2), half) in enumerate(zip(GEOM["bars"], bar_halves(mood, level))):
            cy = (y1 + y2) / 2
            parts.append(f'<line x1="{x}" y1="{cy - half:.3f}" x2="{x}" y2="{cy + half:.3f}" '
                         f'stroke="{accent if i == 4 else bar_c}" '
                         f'stroke-width="{GEOM["barWidth"]}" stroke-linecap="round"/>')
    parts.append("</g></svg>")
    return "".join(parts)


def render(mood: str, side: int, bars: bool = True, level: float = 0.0) -> Image.Image:
    """Rasterise one frame on the screen background."""
    png = subprocess.run(["rsvg-convert", "-b", BG], input=svg(mood, side, bars, level).encode(),
                         capture_output=True, check=True).stdout
    return Image.open(BytesIO(png)).convert("RGB")


def live_bars(side: int) -> tuple[list[tuple[float, ...]], tuple[int, int, int, int], int]:
    """Live bars of the hearing frame in px: per bar the centre relative to
    the bars box, the unit axis and the rest half length; the box (x, y, w, h
    relative to the frame) that holds every bar at full level; the stroke width."""
    k = scale(side)
    c = side / 2
    off = c - GEOM["side"] * k / 2
    ox, oy = GEOM["origin"]
    px, py = PIVOT
    a = math.radians(tilt("hearing"))
    ca, sa = math.cos(a), math.sin(a)

    def to_px(x: float, y: float) -> tuple[float, float]:
        dx, dy = x - px, y - py
        x, y = px + dx * ca - dy * sa, py + dx * sa + dy * ca
        return off + (x - ox) * k, off + (y - oy) * k

    width = GEOM["barWidth"] * k
    bars, xs, ys = [], [], []
    for x, y1, y2 in GEOM["bars"]:
        cx, cy = to_px(x, (y1 + y2) / 2)
        ax, ay = -sa, ca  # the rotated vertical axis
        rest = (y2 - y1) / 2 * k
        bars.append((cx, cy, ax, ay, rest))
        reach = rest + TALK * k * (BASE + SWING)  # full level, crest of the wave
        for sgn in (-1, 1):
            xs.append(cx + sgn * ax * reach)
            ys.append(cy + sgn * ay * reach)
    margin = width / 2  # round caps
    bx, by = math.floor(min(xs) - margin), math.floor(min(ys) - margin)
    bw, bh = math.ceil(max(xs) + margin) - bx, math.ceil(max(ys) + margin) - by
    rel = [(cx - bx, cy - by, ax, ay, rest) for cx, cy, ax, ay, rest in bars]
    return rel, (bx, by, bw, bh), round(width)


def rgb565_le(img: Image.Image) -> bytes:
    out = bytearray()
    for r, g, b in img.get_flattened_data():
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out += bytes((v & 0xFF, v >> 8))
    return bytes(out)


def main() -> int:
    CACHE.mkdir(parents=True, exist_ok=True)
    c = [HEADER, '#include "pocket_mark.h"\n']
    table: dict[str, list[str]] = {k: [] for k in SIZES}
    count = 0
    for size, side in SIZES.items():
        for mood in MOODS:
            if mood not in USED[size]:
                table[size].append("NULL")
                continue
            img = render(mood, side, bars=(size, mood) != LIVE)
            img.save(CACHE / f"{mood}-{side}.png")
            data = rgb565_le(img)
            name = f"pocket_mark_{mood}_{size}"
            rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 24])
                    for i in range(0, len(data), 24)]
            c.append(f"\nstatic const uint8_t {name}_map[] = {{\n    "
                     + ",\n    ".join(rows) + "\n};\n")
            c.append(f"""static const lv_image_dsc_t {name} = {{
    .header.magic = LV_IMAGE_HEADER_MAGIC,
    .header.cf = LV_COLOR_FORMAT_RGB565,
    .header.w = {side},
    .header.h = {side},
    .header.stride = {side * 2},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
""")
            table[size].append(f"&{name}")
            count += 1
    for size in SIZES:
        c.append(f"\nconst lv_image_dsc_t *const pocket_marks_{size}[POCKET_MARK_COUNT] = {{\n    "
                 + ",\n    ".join(table[size]) + ",\n};\n")
    bars, (bx, by, bw, bh), width = live_bars(SIZES["large"])
    c.append("\nconst pocket_mark_bar_t pocket_mark_live_bars[POCKET_MARK_BARS] = {\n"
             + "".join(f"    {{ {cx:.3f}f, {cy:.3f}f, {ax:.5f}f, {ay:.5f}f, {rest:.3f}f }},\n"
                       for cx, cy, ax, ay, rest in bars) + "};\n")
    (SRC / "pocket_mark.c").write_text("".join(c), encoding="utf-8")

    enum = ",\n    ".join(f"POCKET_MARK_{m.upper()}" for m in MOODS)
    k = scale(SIZES["large"])
    h = HEADER + f"""#pragma once

#include "lvgl.h"

// Moods of the web and phone apps. A size holds only the moods it is shown
// in; the others are NULL. Large: state screens; small: the header.
typedef enum {{
    {enum},
    POCKET_MARK_COUNT,
}} pocket_mark_t;

#define POCKET_MARK_LARGE_PX {SIZES['large']}
#define POCKET_MARK_SMALL_PX {SIZES['small']}
extern const lv_image_dsc_t *const pocket_marks_large[POCKET_MARK_COUNT];
extern const lv_image_dsc_t *const pocket_marks_small[POCKET_MARK_COUNT];

// Live voice bars of the large hearing frame (the recording screen), whose
// image has none. Box: px relative to the frame's top-left, holding every bar
// at full level. Per bar: centre relative to the box, unit axis, rest half
// length (px). Colours: bars, and the last bar, the accent.
#define POCKET_MARK_BARS        5
#define POCKET_MARK_BOX_X       {bx}
#define POCKET_MARK_BOX_Y       {by}
#define POCKET_MARK_BOX_W       {bw}
#define POCKET_MARK_BOX_H       {bh}
#define POCKET_MARK_BAR_WIDTH   {width}
#define POCKET_MARK_BAR_RGB     0x{BARS[1:]}
#define POCKET_MARK_ACCENT_RGB  0x{ACCENT[1:]}
// Half length = rest + TALK_PX * level * (BASE + SWING * wave), wave = 0.5 +
// 0.5 * sin(t * RATE + bar * PHASE), level 0..1, t in s: the apps'
// speaking-aloud motion.
#define POCKET_MARK_TALK_PX     {TALK * k:.3f}f
#define POCKET_MARK_TALK_BASE   {BASE}f
#define POCKET_MARK_TALK_SWING  {SWING}f
#define POCKET_MARK_WAVE_RATE   {RATE}f
#define POCKET_MARK_WAVE_PHASE  {PHASE}f

typedef struct {{
    float x, y;     // centre
    float ax, ay;   // unit axis
    float rest;     // half length at rest
}} pocket_mark_bar_t;
extern const pocket_mark_bar_t pocket_mark_live_bars[POCKET_MARK_BARS];
"""
    (SRC / "pocket_mark.h").write_text(h, encoding="utf-8")
    print(f"wrote {count} images, live box {bw}x{bh} at {bx},{by}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
